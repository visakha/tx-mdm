"""Generate frontend/src/b360/api-types.ts from the FastAPI OpenAPI schema (B360 Data models).

Run:   python dev/gen_ts_types.py          (from backend/; or `npm run gen:types` in frontend/)
Check: tests/test_b360_types.py fails when the committed file drifts from the backend models.

A tiny generator instead of openapi-typescript: that package's peer range does not accept the
TypeScript 7 this frontend uses (npm ERESOLVE), and forcing it would change every install.
"""

import sys
from pathlib import Path
from typing import Any

from app.main import create_app

OUT = Path(__file__).resolve().parents[2] / "frontend" / "src" / "b360" / "api-types.ts"
PREFIX = "/api/b360"

HEADER = (
    "// GENERATED by backend/dev/gen_ts_types.py from the backend OpenAPI schema. Do not edit.\n"
    "// Regenerate: cd frontend && npm run gen:types. Drift test: tests/test_b360_types.py\n"
)


def _refs(node: Any, found: set[str]) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str):
            found.add(ref.rsplit("/", 1)[-1])
        for value in node.values():
            _refs(value, found)
    elif isinstance(node, list):
        for value in node:
            _refs(value, found)


def _closure(spec: dict[str, Any]) -> list[str]:
    schemas: dict[str, Any] = spec["components"]["schemas"]
    found: set[str] = set()
    for path, ops in spec["paths"].items():
        if path.startswith(PREFIX):
            for op in ops.values():
                _refs(op.get("responses", {}).get("200", {}), found)
    todo = list(found)
    while todo:
        inner: set[str] = set()
        _refs(schemas[todo.pop()], inner)
        for name in inner - found:
            found.add(name)
            todo.append(name)
    return sorted(found)


def _ts(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in node:
        parts: list[str] = []
        for option in node["anyOf"]:
            text = _ts(option)
            if text not in parts:
                parts.append(text)
        return " | ".join(parts)
    kind = node.get("type")
    if kind == "array":
        inner = _ts(node.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if kind == "object":
        extra = node.get("additionalProperties")
        return (
            f"Record<string, {_ts(extra)}>" if isinstance(extra, dict) else "Record<string, never>"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def render(spec: dict[str, Any]) -> str:
    schemas: dict[str, Any] = spec["components"]["schemas"]
    out = [HEADER]
    for name in _closure(spec):
        schema = schemas[name]
        if "enum" in schema:
            values = " | ".join(f'"{v}"' for v in schema["enum"])
            out.append(f"\nexport type {name} = {values};\n")
            listed = ", ".join(f'"{v}"' for v in schema["enum"])
            out.append(f"export const {name.upper()}_VALUES: readonly {name}[] = [{listed}];\n")
            continue
        required = set(schema.get("required", []))
        out.append(f"\nexport interface {name} {{\n")
        for prop, body in schema.get("properties", {}).items():
            if "description" in body:
                out.append(f"  /** {body['description']} */\n")
            mark = "" if prop in required else "?"
            out.append(f"  {prop}{mark}: {_ts(body)};\n")
        out.append("}\n")
    return "".join(out)


def main() -> int:
    OUT.write_text(render(create_app().openapi()), encoding="ascii", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
